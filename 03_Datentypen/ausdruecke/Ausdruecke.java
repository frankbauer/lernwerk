public class Ausdruecke {
    public static void main(String[] args) {
        System.out.println(12 / (2 + 3));              // Ausgabe: 2
        System.out.println(12 / 5.0);                  // Ausgabe: 2.4
        System.out.println(12.0 / 5);                  // Ausgabe: 2.4
        System.out.println(12.0 / 5.0);                // Ausgabe: 2.4
        System.out.println(73 - 'A');                  // Ausgabe: 8
        System.out.println(8 % 3 == 5 || 'A' < 'B');   // Ausgabe: true
    }
}
