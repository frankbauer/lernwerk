public class Ausdruecke {
    public static void main(String[] args) {
        System.out.println(12 == 5);                 // Ausgabe: false
        System.out.println(12 > 5);                  // Ausgabe: true
        System.out.println(8 % 7 * 2);               // Ausgabe: 2
        System.out.println(12 / (2 + 3));            // Ausgabe: 2
        System.out.println(12 >= 5 == false);        // Ausgabe: false
        System.out.println(7 == 5 == false);         // Ausgabe: true
        System.out.println((7 - 3) == 4 && 7 < 5);   // Ausgabe: false
    }
}
